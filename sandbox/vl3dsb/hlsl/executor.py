"""
Compile & execute the project's HLSL pixel shaders on the CPU.

Pipeline
--------
obj2 script --extract--> HLSL blocks --transpile.py--> C++ (one namespace per
shader) --g++ -O2 -shared--> libvl3d_shaders.so --ctypes--> numpy images

The .so is cached under sandbox/out/build/<hash>/ together with the generated
source, so results are reproducible and the generated code can be inspected
when a shader changes.
"""
from __future__ import annotations

import ctypes
import hashlib
import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from .transpile import HlslError, Parser, tokenize, transpile

HERE = Path(__file__).resolve().parent
RUNTIME_HPP = HERE / "runtime.hpp"

SHADER_RE = re.compile(r"--\[\[pixelshader@([A-Za-z0-9_]+):(.*?)\]\]", re.S)


def extract_shaders(script_text: str) -> Dict[str, str]:
    """Return {shader_name: hlsl_source} for every `--[[pixelshader@name: ...]]` block."""
    out: Dict[str, str] = {}
    for m in SHADER_RE.finditer(script_text):
        out[m.group(1)] = m.group(2)
    return out


@dataclass
class ShaderInfo:
    name: str
    textures: List[str]
    samplers: List[str]
    cb_floats: int


class _VlTex(ctypes.Structure):
    _fields_ = [("w", ctypes.c_int), ("h", ctypes.c_int),
                ("px", ctypes.POINTER(ctypes.c_float))]


class ShaderLibrary:
    """Transpiles + compiles all shaders of one .obj2 script and runs them."""

    def __init__(self, shaders: Dict[str, str], workdir: Optional[Path] = None,
                 cxx: Optional[str] = None):
        if not shaders:
            raise ValueError("no shaders to compile")
        self.shaders = dict(shaders)
        self.workdir = Path(workdir) if workdir else (HERE.parent.parent / "out" / "build")
        self.cxx = cxx or os.environ.get("VL3D_CXX", "g++")
        self.info: Dict[str, ShaderInfo] = {}
        self.generated: Dict[str, str] = {}
        self._prepare()
        self._build()
        self._bind()

    # -- source generation ---------------------------------------------------
    def _prepare(self):
        parts = ["// AUTO-GENERATED by sandbox/vl3dsb/hlsl/executor.py - do not edit",
                 '#include "runtime.hpp"', ""]
        names = sorted(self.shaders)
        for name in names:
            src = self.shaders[name]
            try:
                cpp = transpile(name, src)
            except HlslError as exc:
                raise HlslError(f"transpiling shader '{name}' failed: {exc}") from exc
            self.generated[name] = cpp
            parts.append(cpp)
            parts.append("")
            # collect interface metadata
            prog = Parser(tokenize(src), name).parse_program()
            cb_floats = 0
            for cb in prog["cbuffers"]:
                for f in cb["fields"]:
                    cb_floats += 4 * (f["count"] or 1)
            self.info[name] = ShaderInfo(
                name=name,
                textures=list(prog["textures"]),
                samplers=list(prog["samplers"]),
                cb_floats=cb_floats,
            )
        parts.append("namespace {")
        parts.append("struct Def { const char* name; int (*fn)(int,int,const float*,int,"
                     "const hlsl::vl_tex*,int,unsigned char*); };")
        parts.append("Def g_defs[] = {")
        for name in names:
            parts.append(f'    {{"{name}", sh_{name}::run}},')
        parts.append("};")
        parts.append("const int g_ndefs = (int)(sizeof(g_defs)/sizeof(g_defs[0]));")
        parts.append("}  // namespace")
        parts.append("")
        parts.append('extern "C" int vl_shader_count() { return g_ndefs; }')
        parts.append('extern "C" const char* vl_shader_name(int i) {'
                     ' return (i >= 0 && i < g_ndefs) ? g_defs[i].name : ""; }')
        parts.append("""extern "C" int vl_shader_run(const char* name, int w, int h,
        const float* cb, int ncb, const hlsl::vl_tex* texs, int ntex,
        unsigned char* out, int filter, int address) {
    hlsl::g_filter = filter;
    hlsl::g_address = address;
    for (int i = 0; i < g_ndefs; ++i) {
        if (std::strcmp(g_defs[i].name, name) == 0) return g_defs[i].fn(w, h, cb, ncb, texs, ntex, out);
    }
    return -1;
}""")
        self.source = "\n".join(parts) + "\n"
        digest = hashlib.sha256()
        digest.update(self.source.encode("utf-8"))
        digest.update(RUNTIME_HPP.read_bytes())
        digest.update(b"g++-c++17-v1")
        self.hash = digest.hexdigest()[:16]

    # -- compile -------------------------------------------------------------
    def _build(self):
        self.out_dir = self.workdir / self.hash
        self.out_dir.mkdir(parents=True, exist_ok=True)
        src_path = self.out_dir / "shaders.cpp"
        lib_path = self.out_dir / "libvl3d_shaders.so"
        hdr_path = self.out_dir / "runtime.hpp"
        if not hdr_path.exists() or hdr_path.read_bytes() != RUNTIME_HPP.read_bytes():
            shutil.copyfile(RUNTIME_HPP, hdr_path)
        src_path.write_text(self.source)
        self.build_log = ""
        if not lib_path.exists():
            cmd = [self.cxx, "-std=c++17", "-O2", "-w", "-fPIC", "-shared",
                   str(src_path), "-I", str(self.out_dir), "-o", str(lib_path)]
            proc = subprocess.run(cmd, capture_output=True, text=True)
            self.build_log = proc.stderr
            if proc.returncode != 0:
                raise RuntimeError("failed to compile transpiled shaders:\n" +
                                   self._annotate_errors(proc.stderr))
        self.lib_path = lib_path

    def _annotate_errors(self, stderr: str) -> str:
        """Add a little context (which shader namespace a line belongs to)."""
        lines = self.source.splitlines()
        out = []
        for ln in stderr.splitlines():
            m = re.match(r".*shaders\.cpp:(\d+):(.*)", ln)
            if m:
                no = int(m.group(1)) - 1
                ctx = ""
                for k in range(no, max(0, no - 400), -1):
                    mm = re.match(r"namespace sh_(\w+) \{", lines[k])
                    if mm:
                        ctx = f"  [in shader {mm.group(1)}]"
                        break
                out.append(f"{ln}{ctx}")
                if 0 <= no < len(lines):
                    out.append(f"    > {lines[no]}")
            else:
                out.append(ln)
        return "\n".join(out)

    def _bind(self):
        self.lib = ctypes.CDLL(str(self.lib_path))
        self.lib.vl_shader_count.restype = ctypes.c_int
        self.lib.vl_shader_name.restype = ctypes.c_char_p
        self.lib.vl_shader_name.argtypes = [ctypes.c_int]
        self.lib.vl_shader_run.restype = ctypes.c_int
        self.lib.vl_shader_run.argtypes = [
            ctypes.c_char_p, ctypes.c_int, ctypes.c_int,
            ctypes.POINTER(ctypes.c_float), ctypes.c_int,
            ctypes.POINTER(_VlTex), ctypes.c_int,
            ctypes.c_void_p, ctypes.c_int, ctypes.c_int,
        ]
        n = self.lib.vl_shader_count()
        self.names = [self.lib.vl_shader_name(i).decode() for i in range(n)]

    # -- execution -----------------------------------------------------------
    def run(self, name: str, params: Sequence[float], textures: Sequence[np.ndarray] = (),
            size: Optional[Tuple[int, int]] = None, filter: int = 1, address: int = 0,
            out_hw: Optional[Tuple[int, int]] = None) -> np.ndarray:
        """Execute one pixel shader over a target of `size` (w,h).

        textures: sequence of (h,w,4) float32/uint8 arrays bound to t0..tN.
        Returns (h,w,4) uint8 image, exactly like an AviUtl2 RGBA cache buffer.
        """
        if name not in self.info:
            raise KeyError(f"unknown shader {name!r}; available: {', '.join(self.names)}")
        if out_hw is not None:
            h, w = out_hw
        elif size is not None:
            w, h = size
        else:
            raise ValueError("size or out_hw required")
        w, h = int(w), int(h)
        if w <= 0 or h <= 0:
            return np.zeros((0, 0, 4), np.uint8)
        cb = np.asarray(list(params) or [], dtype=np.float32)
        cb_ptr = cb.ctypes.data_as(ctypes.POINTER(ctypes.c_float)) if cb.size else None

        keep = []
        texs = (_VlTex * max(1, len(textures)))()
        for i, tex in enumerate(textures):
            arr = np.ascontiguousarray(tex)
            if arr.dtype == np.uint8:
                arr = arr.astype(np.float32) / 255.0
            elif arr.dtype != np.float32:
                arr = arr.astype(np.float32)
            if arr.ndim == 2:
                arr = np.stack([arr] * 4, axis=-1)
            if arr.shape[-1] == 3:
                arr = np.concatenate([arr, np.ones(arr.shape[:2] + (1,), np.float32)], axis=-1)
            arr = np.ascontiguousarray(arr, dtype=np.float32)
            keep.append(arr)
            texs[i].w = arr.shape[1]
            texs[i].h = arr.shape[0]
            texs[i].px = arr.ctypes.data_as(ctypes.POINTER(ctypes.c_float))

        out = np.zeros((h, w, 4), dtype=np.uint8)
        rc = self.lib.vl_shader_run(name.encode(), w, h, cb_ptr, int(cb.size),
                                    texs if textures else None, len(textures),
                                    out.ctypes.data_as(ctypes.c_void_p), int(filter), int(address))
        if rc != 0:
            raise RuntimeError(f"shader {name} failed with code {rc}")
        return out

    def describe(self) -> Dict[str, dict]:
        return {n: {"textures": i.textures, "samplers": i.samplers, "cb_floats": i.cb_floats}
                for n, i in self.info.items()}
