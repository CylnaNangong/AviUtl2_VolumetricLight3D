-- 【概要】
-- 任意のレイヤー（画像・動画・テキスト・図形・カスタムオブジェクト等）の明部、
-- または「カメラ制御」内の 3D 光源から、3D 空間へ立体的な光の筋（チンダル現象・体積光）を
-- 放射するカスタムオブジェクトです。
-- ・2D レイヤーおよび 3D モデル（.obj「モデルファイル」／.vrm「VRMToolkitModel」）による
--   3D 影柱（物理遮光）と前景シルエット保護に対応。
-- ・選択した前方 2D レイヤーを背景および 3D 体積光環境へ自然に馴染ませる
--   「前景なじませ（AutoBlendLight 3D 連動）」機能を内蔵（既定 OFF）。
-- ・ネイティブ補助プラグイン「VL3DBridge.aux2」併用時は、無ロック読取ブリッジと
--   Direct3D 11 ComputeShader（cs_5_0）ハードウェア 3D ラスタライザにより、
--   高ポリゴン 3D モデルのリアルタイムドラッグ編集・未保存テキストの文字揃え追従を高速化します
--   （プラグイン未導入環境でも純 LuaJIT FFI へ自動フォールバックして単体動作します）。
--
